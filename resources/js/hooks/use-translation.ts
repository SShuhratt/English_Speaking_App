export function useTranslation() {
    const page = usePage<any>();
    const cookieLocale = typeof document !== 'undefined'
        ? (document.cookie.match(/(?:^|;\s*)locale=([a-z]{2})/)?.[1] as 'en' | 'uz' | 'ru' | undefined)
        : undefined;
    const initialLocale = (cookieLocale || page.props?.locale || 'en') as 'en' | 'uz' | 'ru';
    const [locale, setLocaleState] = useState<'en' | 'uz' | 'ru'>(initialLocale);

    useEffect(() => {
        if (page.props?.locale && page.props.locale !== locale && !cookieLocale) {
            setLocaleState(page.props.locale);
        }
    }, [page.props?.locale]);

    useEffect(() => {
        const handleLocaleChange = (e: CustomEvent<'en' | 'uz' | 'ru'>) => {
            if (e.detail && e.detail !== locale) {
                setLocaleState(e.detail);
            }
        };
        window.addEventListener('locale-changed' as any, handleLocaleChange);
        return () => window.removeEventListener('locale-changed' as any, handleLocaleChange);
    }, [locale]);

    const t = (
        key: string,
        replacementsOrFallback?: Record<string, string | number> | string,
        possibleReplacements?: Record<string, string | number>,
    ) => {
        const langDict =
            dictionary[locale as 'en' | 'uz' | 'ru'] || dictionary.en;
        let val = langDict[key as keyof typeof langDict];

        // Fallback to English dictionary if key missing in current language
        if (val === undefined) {
            val = dictionary.en[key as keyof typeof dictionary.en];
        }

        const fallback =
            typeof replacementsOrFallback === 'string'
                ? replacementsOrFallback
                : undefined;
        const replacements =
            typeof replacementsOrFallback === 'object' &&
            replacementsOrFallback !== null
                ? replacementsOrFallback
                : possibleReplacements;

        let text = val !== undefined ? val : (fallback ?? key);

        // Sanitize raw dev keys (e.g. 'teachers.new_teacher' -> 'New Teacher') so dev tokens never show in UI
        if (text === key && (key.includes('.') || key.includes('_'))) {
            const parts = key.split('.');
            const raw = parts[parts.length - 1];
            text = raw
                .split('_')
                .map(
                    (w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase(),
                )
                .join(' ');
        }

        if (replacements) {
            Object.entries(replacements).forEach(([k, v]) => {
                text = text.replace(new RegExp(`:${k}|\\{${k}\\}`, 'g'), String(v));
            });
        }

        return text;
    };

    const setLanguage = (newLang: 'en' | 'uz' | 'ru') => {
        document.cookie = `locale=${newLang}; path=/; max-age=31536000; SameSite=Lax`;
        setLocaleState(newLang);
        if (typeof window !== 'undefined') {
            window.dispatchEvent(new CustomEvent('locale-changed', { detail: newLang }));
        }
    };

    return { t, locale, setLanguage };
}


